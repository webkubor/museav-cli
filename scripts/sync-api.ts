import fs from 'node:fs'
import path from 'node:path'

const SWAGGER_URL = 'https://modelgo-web-api.test.modelgo.com/swagger/doc.json'
const TYPE_OUTPUT_PATH = path.resolve('src/types/generated-api-types.ts')
const SERVICE_OUTPUT_PATH = path.resolve('src/services/generated-api.ts')

// 格式化类型名，例如 apikey.ListResponse -> ApikeyListResponse
function formatTypeName(name?: string): string {
  if (!name) return 'any'
  return name.split('.')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
    .replace(/[^a-zA-Z0-9_]/g, '')
}

// 转换基本类型
function getPropertyType(prop: any, insideTypeFile = true): string {
  if (!prop) return 'any'
  if (prop.$ref) {
    const typeName = formatTypeName(prop.$ref.split('/').pop())
    return insideTypeFile ? typeName : `ApiTypes.${typeName}`
  }
  
  if (prop.allOf) {
    return prop.allOf.map((item: any) => getPropertyType(item, insideTypeFile)).join(' & ')
  }
  
  switch (prop.type) {
    case 'string':
      if (prop.enum) {
        return prop.enum.map((val: any) => typeof val === 'string' ? `'${val}'` : val).join(' | ')
      }
      return 'string'
    case 'number':
    case 'integer':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'array':
      if (prop.items) {
        return `${getPropertyType(prop.items, insideTypeFile)}[]`
      }
      return 'any[]'
    case 'object':
      if (prop.additionalProperties) {
        return `Record<string, ${getPropertyType(prop.additionalProperties, insideTypeFile)}>`
      }
      if (prop.properties) {
        let inlineObj = '{\n'
        for (const [key, value] of Object.entries(prop.properties)) {
          const isRequired = prop.required && prop.required.includes(key)
          inlineObj += `    ${key}${isRequired ? '' : '?'}: ${getPropertyType(value, insideTypeFile)}\n`
        }
        inlineObj += '  }'
        return inlineObj
      }
      return 'any'
    default:
      return 'any'
  }
}

// 将名称转换为 camelCase
function toCamelCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/[^a-zA-Z0-9]+/g, '')
    .replace(/^(.)/, (_, chr) => chr.toLowerCase())
}

// 获取函数的命名
function getFunctionName(method: string, pathStr: string, operationId?: string): string {
  if (operationId) {
    return toCamelCase(operationId)
  }
  const cleanPath = pathStr.replace(/\{([^}]+)\}/g, 'by_$1')
  const parts = cleanPath.split('/').filter(Boolean)
  const nameStr = [method, ...parts].join('_')
  return toCamelCase(nameStr)
}

// 抽取 Envelope 内的 data 的实际返回值类型
function getResponseType(responses: any, insideTypeFile = true): string {
  if (!responses || !responses['200']) return 'any'
  const schema = responses['200'].schema
  if (!schema) return 'any'
  
  if (schema.allOf) {
    const dataPart = schema.allOf.find((part: any) => part.properties && part.properties.data)
    if (dataPart && dataPart.properties.data) {
      return getPropertyType(dataPart.properties.data, insideTypeFile)
    }
  }
  
  if (schema.properties && schema.properties.data) {
    return getPropertyType(schema.properties.data, insideTypeFile)
  }
  
  return getPropertyType(schema, insideTypeFile)
}

async function main() {
  console.log('Fetching Swagger JSON from:', SWAGGER_URL)
  const res = await fetch(SWAGGER_URL)
  if (!res.ok) {
    throw new Error(`Failed to fetch Swagger JSON: ${res.statusText}`)
  }
  const data = await res.json() as any
  
  const paths = data.paths || {}
  const definitions = data.definitions || {}
  
  // 1. 生成类型文件 (src/types/generated-api-types.ts)
  console.log('Generating types...')
  let typeCode = `/**\n * Auto-generated by scripts/sync-api.ts\n * Do not edit manually.\n */\n\n`
  
  // 先遍历所有的 definitions
  for (const [name, definition] of Object.entries(definitions) as [string, any][]) {
    const typeName = formatTypeName(name)
    const desc = definition.description ? `/** ${definition.description} */\n` : ''
    
    if (definition.type === 'object') {
      typeCode += `${desc}export interface ${typeName} {\n`
      if (definition.properties) {
        for (const [propName, prop] of Object.entries(definition.properties) as [string, any][]) {
          const isRequired = definition.required && definition.required.includes(propName)
          const propDesc = prop.description ? `  /** ${prop.description} */\n` : ''
          typeCode += `${propDesc}  ${propName}${isRequired ? '' : '?'}: ${getPropertyType(prop, true)}\n`
        }
      }
      typeCode += `}\n\n`
    } else {
      typeCode += `${desc}export type ${typeName} = ${getPropertyType(definition, true)}\n\n`
    }
  }
  
  // 额外生成所有 GET / QUERY 接口的 params interface，增加索引签名以兼容 QueryParams
  const queryParamsGenerated: Record<string, string> = {}
  for (const [pathStr, pathItem] of Object.entries(paths) as [string, any][]) {
    for (const [method, operation] of Object.entries(pathItem) as [string, any][]) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue
      
      const funcName = getFunctionName(method, pathStr, operation.operationId)
      const queryParams = (operation.parameters || []).filter((p: any) => p.in === 'query')
      
      if (queryParams.length > 0) {
        const paramTypeName = `${funcName.charAt(0).toUpperCase() + funcName.slice(1)}QueryParams`
        queryParamsGenerated[`${method}:${pathStr}`] = paramTypeName
        
        typeCode += `/** Query parameters for ${funcName} */\n`
        typeCode += `export interface ${paramTypeName} {\n`
        typeCode += `  [key: string]: any;\n` // 完美解决 Index signature for type 'string' is missing 报错
        for (const q of queryParams) {
          const desc = q.description ? `  /** ${q.description} */\n` : ''
          const isRequired = q.required ? '' : '?'
          typeCode += `${desc}  ${q.name}${isRequired}: ${getPropertyType(q, true)}\n`
        }
        typeCode += `}\n\n`
      }
    }
  }
  
  fs.mkdirSync(path.dirname(TYPE_OUTPUT_PATH), { recursive: true })
  fs.writeFileSync(TYPE_OUTPUT_PATH, typeCode, 'utf-8')
  console.log(`Types generated successfully: ${TYPE_OUTPUT_PATH}`)
  
  // 2. 生成 Service 接口请求文件 (src/services/generated-api.ts)
  console.log('Generating service APIs...')
  let serviceCode = `/**\n * Auto-generated by scripts/sync-api.ts\n * Do not edit manually.\n */\n\n`
  serviceCode += `import { get, post, put, patch, del } from '@/lib/request'\n`
  serviceCode += `import * as ApiTypes from '@/types/generated-api-types'\n\n`
  
  for (const [pathStr, pathItem] of Object.entries(paths) as [string, any][]) {
    for (const [method, operation] of Object.entries(pathItem) as [string, any][]) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue
      
      const funcName = getFunctionName(method, pathStr, operation.operationId)
      const parameters = operation.parameters || []
      
      const pathParams = parameters.filter((p: any) => p.in === 'path')
      const bodyParam = parameters.find((p: any) => p.in === 'body')
      const queryParamTypeName = queryParamsGenerated[`${method}:${pathStr}`]
      
      // 组装函数形参
      const argList: string[] = []
      pathParams.forEach((p: any) => {
        argList.push(`${p.name}: string`) // 路径变量通常是 string
      })
      if (bodyParam) {
        argList.push(`body: ${getPropertyType(bodyParam.schema, false)}`)
      }
      if (queryParamTypeName) {
        argList.push(`params?: ApiTypes.${queryParamTypeName}`)
      }
      
      // 组装请求 url 和传递的实参
      const cleanPath = pathStr.replace(/^\/+/, '')
      const templatePath = cleanPath.replace(/\{([^}]+)\}/g, '${$1}')
      const methodMap: Record<string, string> = {
        get: 'get',
        post: 'post',
        put: 'put',
        patch: 'patch',
        delete: 'del'
      }
      
      const requestMethod = methodMap[method]
      const responseType = getResponseType(operation.responses, false)
      
      let callArgs = `\`${templatePath}\``
      if (method === 'get') {
        if (queryParamTypeName) {
          callArgs += `, params`
        }
      } else {
        if (bodyParam) {
          callArgs += `, body`
        } else {
          callArgs += `, undefined` // 完美解决 Expected 2 arguments, but got 1 报错
        }
      }
      
      const summary = operation.summary ? ` * ${operation.summary}\n` : ''
      const desc = operation.description ? ` * ${operation.description}\n` : ''
      
      serviceCode += `/**\n${summary}${desc} */\n`
      serviceCode += `export function ${funcName}(${argList.join(', ')}) {\n`
      serviceCode += `  return ${requestMethod}<${responseType}>(${callArgs})\n`
      serviceCode += `}\n\n`
    }
  }
  
  fs.mkdirSync(path.dirname(SERVICE_OUTPUT_PATH), { recursive: true })
  fs.writeFileSync(SERVICE_OUTPUT_PATH, serviceCode, 'utf-8')
  console.log(`Service APIs generated successfully: ${SERVICE_OUTPUT_PATH}`)
}

main().catch(err => {
  console.error('Error:', err)
  process.exit(1)
})
